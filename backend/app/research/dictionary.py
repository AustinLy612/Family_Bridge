"""Render the research data dictionary as Markdown (docs/research/DATA_DICTIONARY.md).

Generated from the same table specs that build the export, so the two cannot drift; a test and
`python -m app.cli research-dictionary --check` fail when the checked-in file is stale.
"""

from __future__ import annotations

from typing import Any

from app.content.loader import ContentBundle
from app.research.events import EVENTS
from app.research.export import TABLES, Table


class _DictCtx:
    """The minimum `diary_columns` needs: the content bundle (no database)."""

    def __init__(self, content: ContentBundle) -> None:
        self.content = content


def _columns(t: Table, content: ContentBundle) -> list[Any]:
    extra = t.dynamic(_DictCtx(content)) if t.dynamic else []  # type: ignore[arg-type]
    return list(t.columns) + extra


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(content: ContentBundle) -> str:
    out = [
        "# Research data dictionary",
        "",
        "<!-- Generated by `python -m app.cli research-dictionary`; do not edit by hand. -->",
        "",
        "The research export (Plan §5.10) is a zip of CSV files written by the admin **Research",
        "export** screen or `python -m app.cli export-research`. Every download is audited.",
        "",
        "- **Pseudonymous.** People appear only by their random `pseudonym_code`. Groups,",
        "  families, sessions, lessons and homework appear by keyed codes (an HMAC of the",
        "  internal id). The codes stay the same across exports and cannot be reversed without",
        "  the server key. No names, usernames, labels or free text are exported.",
        "- **Separate files for adolescents and caregivers** (`adolescent/`, `caregiver/`).",
        "  `shared/` holds group, family and session tables with no per-person values.",
        "- **Consent (D32, D81).** A participant's record is exported only if it was made",
        "  while their research-export consent was on.",
        "- **Dates (D82).** Each row has a calendar date in the site time zone and a study day",
        "  (day 1 = the day the account was created). No time of day is exported.",
        "- Demo groups, families and accounts are left out unless the export includes demo data.",
        "- Lists are `;`-separated. Empty cells mean no value.",
        "",
        "Column types: `code` (pseudonymous code), `date` (YYYY-MM-DD), `int`, `number`,",
        "`bool` (True/False), `text-enum` (one value from a fixed set), `list`, `json`.",
        "",
    ]
    for scope in ("shared", "adolescent", "caregiver"):
        out += [f"## `{scope}/`", ""]
        for t in (t for t in TABLES if t.scope == scope):
            out += [f"### `{t.path}`", "", t.description, "", f"Source: {t.source}.", ""]
            out += ["| Column | Type | Description |", "|---|---|---|"]
            for c in _columns(t, content):
                out.append(f"| `{c.name}` | {c.type} | {_cell(c.description)} |")
            out.append("")
    out += [
        "## Event types (`events.csv`, `event_types.csv`)",
        "",
        "| Event | Properties | Description |",
        "|---|---|---|",
    ]
    for name, spec in EVENTS.items():
        props = ", ".join(f"`{p}`" for p in spec.props) or "—"
        out.append(f"| `{name}` | {props} | {_cell(spec.description)} |")
    out.append("")
    return "\n".join(out)
