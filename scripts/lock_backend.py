"""Write pinned lock files from the backend venv: runtime closure and full dev set.

Usage (from backend/): .venv/Scripts/python ../scripts/lock_backend.py
"""

from __future__ import annotations

import re
import tomllib
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement


def norm(n: str) -> str:
    return re.sub(r"[-_.]+", "-", n).lower()


def closure(roots: list[str]) -> set[str]:
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        req = Requirement(stack.pop())
        name = norm(req.name)
        if name in seen:
            continue
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            continue
        seen.add(name)
        extras = req.extras or set()
        for dep in dist.requires or []:
            r = Requirement(dep)
            if r.marker is None or any(r.marker.evaluate({"extra": e}) for e in extras | {""}):
                stack.append(dep)
    return seen


def write(path: Path, names: set[str]) -> None:
    lines = sorted(
        f"{d.metadata['Name']}=={d.version}"
        for d in metadata.distributions()
        if norm(d.metadata["Name"]) in names
    )
    path.write_text(
        "# Generated by scripts/lock_backend.py - do not edit by hand.\n" + "\n".join(lines) + "\n",
        encoding="utf-8",
    )


proj = tomllib.loads(Path("pyproject.toml").read_text(encoding="utf-8"))["project"]
runtime = closure(proj["dependencies"])
extras = proj["optional-dependencies"]
dev = runtime | closure(extras["dev"]) | closure(extras["kb-ingest"])  # tests build synthetic PDFs
write(Path("requirements.lock"), runtime)
write(Path("requirements-dev.lock"), dev)
print(f"runtime: {len(runtime)} packages, dev: {len(dev)} packages")
